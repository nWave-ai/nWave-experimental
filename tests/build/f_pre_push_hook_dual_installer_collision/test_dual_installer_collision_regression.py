"""Regression test: pre-push hook dual-installer collision
(fix-pre-push-hook-dual-installer-collision).

RCA: docs/analysis/root-cause-analysis-pre-push-hook-dual-installer-collision.md
Feature delta: docs/feature/fix-pre-push-hook-dual-installer-collision/feature-delta.md

Two independent installers each treat themselves as the sole writer of
`.git/hooks/pre-push`:

1. `pre-commit install` -- the SSOT-intended writer, generates a
   banner-marked script (`# File generated by pre-commit: ...`) -- the
   marker `scripts/validation/verify_hooks.py` checks for.
2. `DESPlugin._install_git_pre_push_backstop`
   (scripts/install/plugins/des_plugin.py:947-1009) -- renames whatever is
   already at `.git/hooks/pre-push` aside to `pre-push.nwave-original` and
   writes its own wrapper (no pre-commit banner) as the live `pre-push`.

The composed real-world state -- pre-commit ran first (the SSOT-intended
writer), the DES plugin's backstop install ran second and chained
pre-commit's output aside per its documented "renames-and-chains" behavior
-- is exactly what `.git/hooks/pre-push` / `.git/hooks/pre-push.nwave-original`
show in THIS repo today. `verify-hooks` (the pre-push gate, PR #78) then
reports the live file as "foreign" (missing the generated-file banner) --
unrelated hardening that happens to trip on the DES backstop's shape.

This test drives the REAL production entry points -- `DESPlugin.
_install_git_pre_push_backstop` (the actual installer method, unmodified)
and `verify_hooks.check_hooks` (the exact pure-core function the
`verify-hooks` pre-push gate calls) -- against a throwaway git repo seeded
with a faithful pre-commit-style banner file, then asserts zero problems.

RED today: the DES wrapper strips the banner, so `check_hooks` reports a
"foreign" problem. GREEN only after the fix folds the backstop into
`.pre-commit-config.yaml` as a `local` hook and retires the DESPlugin call
site (`des_plugin.py:408`), making `pre-commit install` the sole writer.
"""

from __future__ import annotations

import importlib.util
import os
import subprocess
from pathlib import Path
from unittest.mock import MagicMock

import pytest

from scripts.install.plugins.base import InstallContext
from scripts.install.plugins.des_plugin import DESPlugin


# Serializes with other git-hooks-touching tests under `--dist=loadgroup`
# (see .pre-commit-config.yaml pytest-quick-tiers comment) -- this test
# chdirs the process into a throwaway repo while calling the production
# installer method.
pytestmark = pytest.mark.xdist_group("git_hooks")

_REPO_ROOT = Path(__file__).resolve().parents[3]

# A faithful minimal shape of what `pre-commit install` actually writes: the
# generated-file banner as a comment on line 2, directly under the shebang --
# the exact shape `verify_hooks._has_banner_marker` scans for.
_PRECOMMIT_GENERATED_PRE_PUSH = (
    "#!/usr/bin/env bash\n"
    "# File generated by pre-commit: https://pre-commit.com\n"
    "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
    "exec pre-commit hook-impl --hook-type=pre-push\n"
)


def _load_verify_hooks():
    """Load `scripts/validation/verify_hooks.py` as an isolated module.

    Mirrors the loader in `tests/build/unit/test_verify_hooks.py` -- keeps
    the test independent of any `scripts.validation` package import path.
    """
    target = _REPO_ROOT / "scripts" / "validation" / "verify_hooks.py"
    spec = importlib.util.spec_from_file_location("verify_hooks", target)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _init_repo(repo_dir: Path) -> None:
    """Initialize a throwaway git repository -- no real-repo writes."""
    repo_dir.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["git", "init", "-q", "-b", "main"], cwd=repo_dir, check=True, timeout=10
    )


def test_verify_hooks_passes_after_both_installers_run_in_sequence(
    tmp_path: Path,
) -> None:
    """Both installers touching `.git/hooks/pre-push` in sequence must still
    leave a `verify-hooks`-clean file.

    Sequence (matches the composed real-world state -- and this repo's
    actual `.git/hooks/pre-push` today):
      1. pre-commit install runs first -- writes the banner-marked script
         (simulated here as a faithful fixture; running the real
         `pre-commit` binary is not required to reproduce the collision --
         the marker shape is exactly what `verify_hooks` inspects).
      2. `DESPlugin._install_git_pre_push_backstop` runs second, as its
         real, unmodified production method -- sees the existing banner
         file, renames it aside to `pre-push.nwave-original`, writes its
         own wrapper as the live `pre-push`.

    `verify_hooks.check_hooks` -- the exact pure-core function the
    `verify-hooks` pre-push gate calls -- must report zero problems for the
    resulting `pre-push`. Today it does not.
    """
    repo_dir = tmp_path / "collision-repo"
    _init_repo(repo_dir)
    hooks_dir = repo_dir / ".git" / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)

    # Step 1: pre-commit install writes the banner-marked pre-push.
    (hooks_dir / "pre-push").write_text(_PRECOMMIT_GENERATED_PRE_PUSH, encoding="utf-8")
    (hooks_dir / "pre-push").chmod(0o755)

    # Step 2: DESPlugin's real backstop installer runs on top of it.
    context = InstallContext(
        claude_dir=tmp_path / "claude_home",
        scripts_dir=tmp_path / "scripts",
        templates_dir=tmp_path / "templates",
        logger=MagicMock(),
        project_root=repo_dir,
        framework_source=tmp_path / "framework_source",
        dry_run=False,
    )
    plugin = DESPlugin()
    original_cwd = Path.cwd()
    try:
        os.chdir(repo_dir)
        result = plugin._install_git_pre_push_backstop(context)
    finally:
        os.chdir(original_cwd)
    assert result.success, f"backstop install itself failed: {result.message}"

    # Assert via the REAL verify-hooks pure core -- the same function the
    # pre-push gate calls.
    vh = _load_verify_hooks()

    def reader(hook_type: str) -> str | None:
        path = hooks_dir / hook_type
        if not path.is_file():
            return None
        return path.read_text(encoding="utf-8", errors="replace")

    problems = vh.check_hooks(["pre-push"], hooks_dir, None, reader)

    assert problems == [], (
        "verify-hooks must report zero problems after both installers run "
        "in sequence (RCA fix-pre-push-hook-dual-installer-collision); got: "
        f"{problems!r}"
    )
