def test_successful_reverify_appends_adjacent_slice_reverified_provenance(
    orphaned_green_slice_repo: tuple[Path, str],
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Criterion 3: a successful reverify appends a `SliceReverified` record.

    The success path appends TWO adjacent HMAC-chained ledger records: the
    `SliceCommitVerified` record (M8-visible) and a `SliceReverified`
    provenance record (I-6). `verified_slices()` keys only on
    `SliceCommitVerified`, so its shape is unchanged -- the provenance
    record makes the recovery path auditable without altering ordering.
    """
    repo, slice_sha = orphaned_green_slice_repo

    ledger = AtCompletionLedger(_FEATURE_ID, repo)
    verified_before = ledger.verified_slices()

    exit_code = main(_argv(repo, "slice-01", slice_sha))
    assert exit_code == 0
    capsys.readouterr()

    records_after = ledger.read_records()
    # A genuine SliceReverified provenance record is appended.
    provenance = [r for r in records_after if r["event"] == "SliceReverified"]
    assert any(r["slice_id"] == "slice-01" for r in provenance)
    # It is adjacent to the SliceCommitVerified record (the chain reads back
    # intact under M7 -- read_records would raise on a broken HMAC chain).
    verified_records = [r for r in records_after if r["event"] == "SliceCommitVerified"]
    assert verified_records
    verified_seq = max(r["seq"] for r in verified_records)
    provenance_seq = max(r["seq"] for r in provenance)
    assert provenance_seq == verified_seq + 1

    # verified_slices() shape is unchanged -- it keys only on
    # SliceCommitVerified, so the provenance record is M8-invisible.
    verified_after = ledger.verified_slices()
    assert verified_after == verified_before | {"slice-01"}
