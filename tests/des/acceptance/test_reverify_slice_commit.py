# --------------------------------------------------------------------------
# Step 01-07 -- Precondition P6: predecessor-verified + SliceReverified
# provenance.
#
# P6 closes the carpaccio ordering hole: reverify of `slice-N` (N > 1) is
# refused when `slice-(N-1)` carries no `SliceCommitVerified` ledger record.
# Without P6 a reverify could mint an out-of-order `SliceCommitVerified`
# record, leaving a permanent M8-invisible hole (the U1 M8 carpaccio-order
# check keys on `SliceCommitVerified`). P6 mirrors the U1 M8 order check --
# immediate predecessor only, zero-padding-preserving -- and runs in the
# precondition group after P5, before any gate.
#
# The success path additionally appends an adjacent HMAC-chained
# `SliceReverified` provenance record (I-6): `verified_slices()` keys only
# on `SliceCommitVerified`, so the provenance record makes the recovery
# path auditable in the integrity log WITHOUT changing carpaccio ordering.
# --------------------------------------------------------------------------


@pytest.fixture
def slice_02_predecessor_unverified_repo(tmp_path: Path) -> tuple[Path, str]:
    """A temp-git repo with a buried `slice-02` whose `slice-01` is unverified.

    History (oldest -> newest):
      1. base commit (pytest.ini).
      2. SLICE-02 COMMIT -- carries the `@slice-02` `.feature` + `Slice-Id`
         trailer. This is the buried slice being reverified.
      3. a later commit grows the contract suite (so the slice-02 commit is
         genuinely buried -- P5 passes).

    The ledger carries NO `SliceCommitVerified` record for `slice-01`. P6
    must refuse: reverify of `slice-02` cannot precede its predecessor.

    Returns ``(repo, slice_02_commit_sha)``.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    _init_repo(repo)

    (repo / "pytest.ini").write_text(_TEMP_PYTEST_INI, encoding="utf-8")
    _commit(repo, "chore: base\n")

    features = repo / "tests" / "acceptance"
    features.mkdir(parents=True)
    (features / "slice_02.feature").write_text(
        _SLICE_FEATURE.replace("@slice-01", "@slice-02"), encoding="utf-8"
    )
    slice_sha = _commit(repo, "feat: walking skeleton slice-02\n\nSlice-Id: slice-02\n")

    (repo / "tests" / "test_contract.py").write_text(
        _CONTRACT_TEST_GREEN, encoding="utf-8"
    )
    _commit(repo, "test: add contract test after the slice commit\n")

    return repo, slice_sha


