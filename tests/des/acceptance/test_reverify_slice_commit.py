# Step 01-06 -- Precondition P5: orphan-state.
#
# P5 confines reverify to a GENUINELY-ORPHANED (buried) slice -- a commit
# that is a STRICT ancestor of HEAD with at least one commit between it and
# HEAD. Without P5, reverify emits the identical `SliceCommitVerified` record
# the U2 G_COMMIT exit gate emits, callable at will even on a still-HEAD
# commit -- a routine-bypass vector (feature-delta sec.13 R-6, Residuality
# Pass S1 "reverify-as-bypass-vector"). P5 makes reverify and the U2 exit
# gate own DISJOINT mechanically-enforced domains: a still-HEAD slice is
# structurally unavailable to reverify. P5 runs in the precondition group,
# after P4, before any gate.
# --------------------------------------------------------------------------


@pytest.fixture
def slice_commit_is_head_repo(tmp_path: Path) -> tuple[Path, str]:
    """A temp-git repo whose slice commit IS HEAD (no commit buries it).

    History (oldest -> newest):
      1. base commit (pytest.ini).
      2. SLICE COMMIT -- carries the `@slice-01` `.feature` + `Slice-Id`
         trailer. This is HEAD: nothing is committed after it.

    The slice commit is an ancestor of HEAD only in the reflexive sense
    (it IS HEAD). P5 must refuse -- a still-HEAD slice is owned by the U2
    G_COMMIT exit gate, not reverify.

    Returns ``(repo, slice_commit_sha)`` where ``slice_commit_sha == HEAD``.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    _init_repo(repo)

    (repo / "pytest.ini").write_text(_TEMP_PYTEST_INI, encoding="utf-8")
    _commit(repo, "chore: base\n")

    features = repo / "tests" / "acceptance"
    features.mkdir(parents=True)
    (features / "slice_01.feature").write_text(_SLICE_FEATURE, encoding="utf-8")
    (repo / "tests" / "test_contract.py").write_text(
        _CONTRACT_TEST_GREEN, encoding="utf-8"
    )
    slice_sha = _commit(repo, "feat: walking skeleton slice-01\n\nSlice-Id: slice-01\n")

    return repo, slice_sha


