def _git(repo: Path, *args: str) -> str:
    """Run a git command in ``repo`` and return stdout."""
    return subprocess.run(
        ["git", *args], cwd=repo, capture_output=True, text=True, check=True
    ).stdout


def _init_repo(repo: Path) -> None:
    """Initialise a git repo with deterministic identity."""
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.email", "t@t"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.name", "t"], cwd=repo, check=True)


def _commit(repo: Path, message: str) -> str:
    """Stage everything and commit with ``message``; return the commit SHA."""
    subprocess.run(["git", "add", "-A"], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-q", "-m", message], cwd=repo, check=True)
    return _git(repo, "rev-parse", "HEAD").strip()


def _argv(repo: Path, slice_id: str, commit: str) -> list[str]:
    return [
        "--repo",
        str(repo),
        "--feature-id",
        _FEATURE_ID,
        "--slice-id",
        slice_id,
        "--commit",
        commit,
    ]


@pytest.fixture
def orphaned_green_slice_repo(tmp_path: Path) -> tuple[Path, str]:
    """A temp-git repo with a buried green slice + a later contract test.

    History (oldest -> newest):
      1. base commit (pytest.ini so the contract suite is collectable).
      2. SLICE COMMIT -- carries the @slice-01 .feature file + ``Slice-Id``
         trailer. This is the buried slice being reverified.
      3. a later commit that ADDS a contract-marked test -- the suite has
         grown since the slice commit (exercises criterion 3 / R-3).

    Returns ``(repo, slice_commit_sha)``.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    _init_repo(repo)

    # 1. base commit -- the temp repo's own pytest config.
    (repo / "pytest.ini").write_text(_TEMP_PYTEST_INI, encoding="utf-8")
    _commit(repo, "chore: base\n")

    # 2. the slice commit -- the @slice-01 .feature AT lives here.
    features = repo / "tests" / "acceptance"
    features.mkdir(parents=True)
    (features / "slice_01.feature").write_text(_SLICE_FEATURE, encoding="utf-8")
    slice_sha = _commit(repo, "feat: walking skeleton slice-01\n\nSlice-Id: slice-01\n")

    # 3. a LATER commit grows the contract suite (criterion 3 / R-3).
    (repo / "tests" / "test_contract.py").write_text(
        _CONTRACT_TEST_GREEN, encoding="utf-8"
    )
    _commit(repo, "test: add contract test after the slice commit\n")

    return repo, slice_sha


def test_both_gates_pass_appends_genuine_slice_commit_verified_exit_0(
    orphaned_green_slice_repo: tuple[Path, str],
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Criteria 1+2+3: both real gates pass -> SliceCommitVerified, exit 0.

    The slice commit carries its @slice-01 .feature file (E1 passes against
    the working tree) and the contract suite -- grown since the commit --
    runs genuinely green (E2 passes). The success path appends a real
    ``SliceCommitVerified`` ledger record through ``append_gate_event``;
    the HMAC chain reads back intact under the M7 fail-closed contract.
    """
    repo, slice_sha = orphaned_green_slice_repo

    ledger = AtCompletionLedger(_FEATURE_ID, repo)
    records_before = len(ledger.read_records())

    exit_code = main(_argv(repo, "slice-01", slice_sha))

    assert exit_code == 0
    payload = json.loads(capsys.readouterr().out.strip())
    assert payload["event"] == "SliceReverified"

    # Criterion 2: a genuine SliceCommitVerified record was appended, and the
    # whole chain reads back intact under M7 (no LedgerIntegrityViolation).
    records_after = ledger.read_records()
    assert len(records_after) > records_before
    verified = ledger.verified_slices()
    assert "slice-01" in verified
    appended = [r for r in records_after if r["event"] == "SliceCommitVerified"]
    assert any(r["slice_id"] == "slice-01" for r in appended)


