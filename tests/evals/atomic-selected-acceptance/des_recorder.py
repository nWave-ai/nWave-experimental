"""Per-invocation recorder used as the probe's `des` shim (instrument control, not product proof).

Environment (set by run_probe.host_environment):
  DES_RECORD_LOG      private per-run JSONL path (one record per actual shim call)
  DES_RECORD_HANDOVER absolute path of the handover file hashed before/after each call
  DES_RECORD_TESTS    optional tests/ directory hashed before each call (support-repair evidence)
  DES_RECORD_REDACT_NAMES  comma list of credential env NAMES whose exact values are redacted in records
  DES_RECORD_REAL     JSON argv prefix of the real des (e.g. [des_python, "-m", "des.cli"])
  Path-independent interception: PATH order is not reliable (host shell startup put the installed
  .claude/bin/des first). The probe therefore also sets PYTHONPATH to a generated sitecustomize
  (INTERCEPT_HOOK): when the installed `des` python script starts, it re-execs this recorder, which
  runs that very installed script (DES_RECORD_INTERCEPTED). No installed/source byte is changed.
  Limit: a caller that bypasses the script (`python -m des.cli`) or clears PYTHONPATH is not seen;
  the transcript/record count mismatch still makes such a run indeterminate.
Stdin is captured only when the command reads it (`--input -` / `--input=-`); otherwise it is
inherited untouched so state/help never block. No environment values are recorded.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path


def digest(path: str) -> str:
    p = Path(path)
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else "absent"


def reads_stdin(argv: list[str]) -> bool:
    return "--input=-" in argv or any(
        a == "--input" and i + 1 < len(argv) and argv[i + 1] == "-"
        for i, a in enumerate(argv)
    )


def redact(value: str, secrets: list[str]) -> str:
    """Replace the exact values of passed credential env vars (never names or other text)."""
    for secret in secrets:
        if secret:
            value = value.replace(secret, "[REDACTED]")
    return value


def credential_values() -> list[str]:
    names = [n for n in os.environ.get("DES_RECORD_REDACT_NAMES", "").split(",") if n]
    return [os.environ[n] for n in names if os.environ.get(n)]


def tree_digest(path: str) -> str:
    root = Path(path)
    h = hashlib.sha256()
    for p in sorted(root.rglob("*")) if root.is_dir() else []:
        if p.is_file() and "__pycache__" not in p.parts:
            h.update(str(p.relative_to(root)).encode())
            h.update(p.read_bytes())
    return h.hexdigest()


def text(data: bytes) -> str:
    return redact(data.decode("utf-8", errors="replace"), credential_values())


INTERCEPT_HOOK = """\
# Generated by the probe (instrument, not product). Loaded via PYTHONPATH by any python process.
# If that process is the installed `des` script, hand it to the recorder, which runs that same script.
import os, sys
_script = sys.argv[0] if sys.argv else ""
if (os.environ.get("DES_RECORD_INTERCEPT") and not os.environ.get("DES_RECORD_ACTIVE")
        and os.path.basename(_script) == "des" and os.path.isfile(_script)):
    os.environ["DES_RECORD_ACTIVE"] = "1"
    os.environ["DES_RECORD_INTERCEPTED"] = os.path.abspath(_script)
    os.execv(sys.executable, [sys.executable, os.environ["DES_RECORD_RECORDER"], *sys.argv[1:]])
"""


def main(argv: list[str]) -> int:
    intercepted = os.environ.pop("DES_RECORD_INTERCEPTED", None)
    real = (
        [sys.executable, intercepted]
        if intercepted
        else json.loads(os.environ["DES_RECORD_REAL"])
    )
    handover = os.environ["DES_RECORD_HANDOVER"]
    before = digest(handover)
    tests_before = (
        tree_digest(os.environ["DES_RECORD_TESTS"])
        if os.environ.get("DES_RECORD_TESTS")
        else None
    )
    captured = sys.stdin.buffer.read() if reads_stdin(argv) else None
    done = subprocess.run(real + argv, input=captured, capture_output=True)
    after = digest(handover)
    record = {
        "argv": ["des", *argv],
        "stdin": None if captured is None else text(captured),
        "stdin_captured": captured is not None,
        "exit": done.returncode,
        "stdout": text(done.stdout),
        "stderr": text(done.stderr),
        "stdout_sha256": hashlib.sha256(done.stdout).hexdigest(),
        "stderr_sha256": hashlib.sha256(done.stderr).hexdigest(),
        "handover_before": before,
        "handover_after": after,
        "tests_before": tests_before,
    }
    fd = os.open(
        os.environ["DES_RECORD_LOG"], os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600
    )
    try:
        os.write(fd, (json.dumps(record) + "\n").encode())
    finally:
        os.close(fd)
    sys.stdout.buffer.write(
        done.stdout
    )  # host sees real output; the stored record is redacted
    sys.stdout.flush()
    sys.stderr.buffer.write(done.stderr)
    sys.stderr.flush()
    return done.returncode


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
